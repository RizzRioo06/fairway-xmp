import { useState } from 'react';
import type { Column, Row } from './types';

type Field = { mode: 'default' | 'null' | 'value'; value: string };

const canUseDefault = (column: Column) => /auto_increment/i.test(column.extra) || column.defaultValue !== null;
const insertMode = (column: Column): Field['mode'] => canUseDefault(column) ? 'default' : column.nullable ? 'null' : 'value';
// Match the visible initial fields even when Save is clicked without editing them.
export function initialInsertValues(columns: Column[]): Row {
  return Object.fromEntries(columns.filter(c => !c.generated && !c.binary && !canUseDefault(c)).map(c => [c.name, c.nullable ? null : '']));
}

function startingField(column: Column, original?: Row): Field {
  if (!original) return { mode: insertMode(column), value: '' };
  return original[column.name] === null ? { mode: 'null', value: '' } : { mode: 'value', value: original[column.name] ?? '' };
}

export default function RowFields({ columns, original, onChange }: { columns: Column[]; original?: Row; onChange: (row: Row) => void }) {
  const [fields, setFields] = useState(() => Object.fromEntries(columns.map(c => [c.name, startingField(c, original)])));
  function change(name: string, field: Field) {
    const next = { ...fields, [name]: field }; setFields(next);
    const values: Row = {};
    for (const c of columns) if (!c.generated && !c.binary && next[c.name].mode !== 'default') {
      const value = next[c.name].mode === 'null' ? null : next[c.name].value;
      if (!original || value !== original[c.name]) values[c.name] = value;
    }
    onChange(values);
  }
  // Blank nullable text is NULL. Choosing Value while blank keeps an empty string.
  function choose(column: Column, mode: Field['mode']) {
    const current = fields[column.name];
    change(column.name, mode === 'value' ? { mode, value: current.mode === 'value' ? current.value : '' } : { mode, value: '' });
  }
  return <div className="db-row-fields">{columns.map(c => {
    const field = fields[c.name];
    return <div key={c.name} className="db-row-field"><label htmlFor={`row-${c.name}`}>{c.name}<small>{c.type}{c.columnKey === 'PRI' ? ' · primary key' : ''}{c.generated || c.binary ? ' · read-only' : ''}</small></label>
      {c.generated || c.binary ? <code>{original?.[c.name] ?? (c.binary ? 'Binary value · use SQL' : 'Generated by the database')}</code> : <>
        <select aria-label={`${c.name} value mode`} value={field.mode} onChange={e => choose(c, e.target.value as Field['mode'])}>{!original && canUseDefault(c) && <option value="default">{/auto_increment/i.test(c.extra) ? 'Auto' : 'Use default'}</option>}<option value="value">Value</option>{c.nullable && <option value="null">NULL</option>}</select>
        <textarea id={`row-${c.name}`} aria-label={`${c.name} value`} rows={2} disabled={field.mode === 'default'} value={field.value} onChange={e => change(c.name, { mode: c.nullable && e.target.value === '' ? 'null' : 'value', value: e.target.value })} placeholder={field.mode === 'null' ? 'Leave blank for NULL' : field.mode === 'value' ? 'Empty text is an empty string' : 'Let the database supply this value'} />
      </>}
    </div>;
  })}</div>;
}
