import { expect, test } from '@playwright/test';

test('SQLite is discoverable with stopped services and shares the table editor', async ({ page }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Browse Data', exact: true }).click();
  const openFile = page.getByRole('button', { name: 'Open SQLite file…', exact: true });
  await expect(openFile).toBeEnabled();
  await expect(page.getByText('Browse your MySQL databases and SQLite files.', { exact: true })).toBeVisible();
  const mysqlTab = page.getByRole('tab', { name: 'MySQL', exact: true });
  const sqliteTab = page.getByRole('tab', { name: 'SQLite', exact: true });
  await expect(mysqlTab).toBeEnabled();
  await expect(sqliteTab).toBeEnabled();
  await expect(mysqlTab).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByLabel('SQLite file path', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Start MySQL to browse your data', exact: true })).toBeVisible();
  await sqliteTab.click();
  await expect(sqliteTab).toHaveAttribute('aria-selected', 'true');
  await expect(openFile).toBeEnabled();
  await expect(page.getByRole('heading', { name: 'Open a SQLite file to browse your data', exact: true })).toBeVisible();
  await expect(page.getByLabel('SQLite file path', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Start MySQL', exact: true })).toHaveCount(0);
  await mysqlTab.click();
  await expect(page.getByRole('heading', { name: 'Start MySQL to browse your data', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start MySQL', exact: true })).toBeEnabled();
  await sqliteTab.click();
  await page.getByRole('button', { name: 'Open SQLite file', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'MySQL', exact: true })).toBeEnabled();
  await expect(page.getByRole('tab', { name: 'SQLite', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('tab', { name: 'SQLite', exact: true })).toHaveText('SQLite');
  const fileCard = page.getByRole('region', { name: 'SQLite file', exact: true });
  const sourceTabs = page.getByRole('tablist', { name: 'Data source', exact: true });
  await expect(fileCard.getByLabel('SQLite file path', { exact: true })).toHaveText('/Users/Student May/projects/classroom/database.sqlite');
  await expect(fileCard.getByText('Editing the original project file. Changes are saved immediately.', { exact: true })).toBeVisible();
  await expect(fileCard.getByRole('button', { name: 'Back up SQLite file', exact: true })).toBeEnabled();
  await expect(fileCard.getByRole('button', { name: 'Close SQLite file', exact: true })).toBeEnabled();
  await expect(sourceTabs.getByRole('button', { name: 'Back up SQLite file', exact: true })).toHaveCount(0);
  await expect(sourceTabs.getByRole('button', { name: 'Close SQLite file', exact: true })).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => {
    const tabs = document.querySelector('.db-source-tabs');
    const card = document.querySelector('.db-file-card');
    return !!(tabs && card && tabs.compareDocumentPosition(card) & Node.DOCUMENT_POSITION_FOLLOWING && tabs.closest('.db-source') === card.closest('.db-source') && !tabs.contains(card));
  })).toBe(true);
  await expect(page.getByRole('button', { name: 'Start MySQL', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Database actions', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Create table', exact: true }).first().click();
  let dialog = page.getByRole('dialog', { name: 'Create table', exact: true });
  await dialog.getByLabel('Table name', { exact: true }).fill('students');
  await expect(dialog.getByRole('combobox', { name: 'Type', exact: true }).first()).toHaveValue('INTEGER');
  await expect(dialog.getByRole('combobox', { name: 'Type', exact: true }).last()).toHaveValue('TEXT');
  await expect(dialog.getByLabel('Unsigned', { exact: true })).toHaveCount(0);
  await expect(dialog.locator('.db-column-card').nth(1).getByLabel('Allow NULL', { exact: true })).toBeChecked();
  await dialog.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('button', { name: 'Insert row', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Insert row', exact: true });
  await dialog.getByLabel('name value mode', { exact: true }).selectOption('value');
  await dialog.getByLabel('name value', { exact: true }).fill('SQLite Student 日本');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Table rows', exact: true })).toContainText('SQLite Student 日本');
  await page.getByRole('tab', { name: 'Structure', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit column name', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Environment', exact: true }).click();
  await page.getByRole('button', { name: 'Browse Data', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Table structure', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back up SQLite file', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('SQLite backup saved:');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const screenshot = info.outputPath('sqlite-browser.png');
  await page.screenshot({ path: screenshot, fullPage: true });
  await info.attach('sqlite-browser', { path: screenshot, contentType: 'image/png' });
  await mysqlTab.click();
  await expect(page.getByRole('heading', { name: 'Start MySQL to browse your data', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start MySQL', exact: true })).toBeEnabled();
  await expect(page.getByLabel('SQLite file path', { exact: true })).toHaveCount(0);
  await sqliteTab.click();
  await expect(page.getByLabel('SQLite file path', { exact: true })).toHaveText('/Users/Student May/projects/classroom/database.sqlite');
  await expect(fileCard.getByRole('button', { name: 'Back up SQLite file', exact: true })).toBeVisible();
  await page.evaluate(() => {
    const win = window as Window & { __sqlitePicks?: number };
    win.__sqlitePicks = 0;
    window.addEventListener('fairway-ui-command', event => {
      if ((event as CustomEvent).detail === 'pick_sqlite_file') win.__sqlitePicks = (win.__sqlitePicks ?? 0) + 1;
    });
  });
  await page.getByRole('button', { name: 'Close SQLite file', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Open a SQLite file to browse your data', exact: true })).toBeVisible();
  await expect(page.getByLabel('SQLite file path', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Back up SQLite file', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Open SQLite file', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Reopen database.sqlite', exact: true })).toBeEnabled();
  expect(await page.evaluate(() => localStorage.getItem('fairway.sqlite.recent.v1'))).toContain('/Users/Student May/projects/classroom/database.sqlite');
  await mysqlTab.click();
  await expect(page.getByRole('heading', { name: 'Start MySQL to browse your data', exact: true })).toBeVisible();
  await sqliteTab.click();
  await expect(page.getByRole('heading', { name: 'Open a SQLite file to browse your data', exact: true })).toBeVisible();
  await expect(page.getByLabel('SQLite file path', { exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => (window as Window & { __sqlitePicks?: number }).__sqlitePicks ?? 0)).toBe(0);
  await page.getByRole('button', { name: 'Reopen database.sqlite', exact: true }).click();
  await expect(fileCard.getByLabel('SQLite file path', { exact: true })).toHaveText('/Users/Student May/projects/classroom/database.sqlite');
  await expect(fileCard.getByRole('button', { name: 'Close SQLite file', exact: true })).toBeEnabled();
  expect(await page.evaluate(() => (window as Window & { __sqlitePicks?: number }).__sqlitePicks ?? 0)).toBe(0);
  await page.getByLabel('Scenario', { exact: true }).selectOption('Running');
  await expect(page.getByRole('tab', { name: 'MySQL', exact: true })).toBeEnabled();
  await page.getByRole('tab', { name: 'MySQL', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Database', exact: true })).toBeEnabled();
  await page.reload();
  await page.getByRole('button', { name: 'Browse Data', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'SQLite', exact: true })).toBeEnabled();
  await page.getByRole('tab', { name: 'SQLite', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Back up SQLite file', exact: true })).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
});
