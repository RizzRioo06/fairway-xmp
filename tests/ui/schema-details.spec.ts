import { expect, test } from '@playwright/test';

test('Structure manages ordered indexes and inspects incoming and outgoing foreign keys', async ({ page }, info) => {
  await page.goto('/');
  await page.getByLabel('Scenario', { exact: true }).selectOption('Running');
  await page.getByRole('button', { name: 'Browse Data', exact: true }).click();
  await page.getByRole('tab', { name: 'Structure', exact: true }).click();
  const indexes = page.getByRole('region', { name: 'Indexes', exact: true });
  await expect(indexes).toContainText('Primary key');
  const foreignKeys = page.getByRole('region', { name: 'Foreign keys', exact: true });
  await expect(foreignKeys).toContainText('enrollments.student_id → students.id');
  await expect(foreignKeys).toContainText('On delete: CASCADE');
  await page.getByRole('button', { name: 'Index', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Create index', exact: true });
  await dialog.getByLabel('Index column 1', { exact: true }).selectOption('name');
  await dialog.getByLabel('Require unique values', { exact: true }).check();
  await dialog.getByRole('button', { name: 'Add index column', exact: true }).click();
  await dialog.getByRole('button', { name: 'Move index column 2 up', exact: true }).click();
  await expect(dialog.getByLabel('Index name', { exact: true })).toHaveValue('uq_students_id_name');
  await dialog.getByLabel('Index name', { exact: true }).fill('student_lookup');
  await dialog.getByRole('button', { name: 'Move index column 2 up', exact: true }).click();
  await expect(dialog.getByLabel('Index name', { exact: true })).toHaveValue('student_lookup');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await dialog.getByRole('button', { name: 'Create', exact: true }).click();
  const item = indexes.locator('li').filter({ has: page.getByText('student_lookup', { exact: true }) });
  await expect(item).toContainText('Unique');
  await expect(item.locator('.db-index-parts code')).toHaveText(['name', 'id']);
  const screenshot = info.outputPath('schema-details.png');
  await page.screenshot({ path: screenshot, fullPage: true });
  await info.attach('schema-details', { path: screenshot, contentType: 'image/png' });
  await item.getByRole('button', { name: 'Remove index student_lookup', exact: true }).click();
  const removal = page.getByRole('dialog', { name: 'Remove index', exact: true });
  await expect(removal.getByRole('button', { name: 'Remove', exact: true })).toBeDisabled();
  await removal.getByLabel('Type student_lookup to confirm', { exact: true }).fill('student_lookup');
  await removal.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(item).toHaveCount(0);
  await expect(indexes.getByRole('button', { name: 'Remove index PRIMARY', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'enrollments', exact: true }).click();
  await expect(foreignKeys).toContainText('fk_enrollments_student');
  await expect(foreignKeys).toContainText('enrollments.student_id → students.id');
});
